// 난이도별로 무작위 n문항 뽑기
function pickQuestions(level, n = 10) {
  const pool = [...QUESTIONS[level]];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, n);
}
